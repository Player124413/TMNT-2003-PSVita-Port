package org.tmnt.port;

import android.content.Context;
import android.content.SharedPreferences;
import java.io.File;
import java.io.FileOutputStream;
import java.nio.charset.StandardCharsets;

/** Persisted launch options; native code reads a small allow-listed environment file. */
public final class PortSettings {
    public static final int BALANCED = 0, COOL = 1, PERFORMANCE = 2;
    private final SharedPreferences prefs;
    public PortSettings(Context context) {
        prefs = context.getSharedPreferences("port", Context.MODE_PRIVATE);
    }
    public int profile() { return prefs.getInt("profile", BALANCED); }
    public boolean aspect43() { return prefs.getBoolean("aspect43", true); }
    public boolean sound() { return prefs.getBoolean("sound", true); }
    public boolean perf() { return prefs.getBoolean("perf", false); }
    public boolean haptics() { return prefs.getBoolean("haptics", true); }
    public float scale() { return prefs.getFloat("scale", 0.75f); }
    public float deadzone() { return prefs.getFloat("deadzone", 0.16f); }
    public void put(String key, Object value) {
        SharedPreferences.Editor e = prefs.edit();
        if (value instanceof Boolean) e.putBoolean(key, (Boolean)value);
        else if (value instanceof Integer) e.putInt(key, (Integer)value);
        else if (value instanceof Float) e.putFloat(key, (Float)value);
        e.apply();
    }
    public void writeNative(Context context) throws Exception {
        int p = profile();
        String text = "# Generated by the TMNT launcher. Restart the game after changes.\n"
            + "TMNT_AUDIO=" + (sound() ? 1 : 0) + "\n"
            + "TMNT_ASPECT=" + (aspect43() ? "4:3" : "stretched") + "\n"
            + "TMNT_PERF=" + (perf() ? 1 : 0) + "\n"
            + "TMNT_RENDER_SCALE=" + Math.max(0.25f, Math.min(1f, scale())) + "\n"
            + "TMNT_PAR=" + (p == COOL ? 0 : 2) + "\n"
            + "TMNT_RENDER_THREAD=" + (p == COOL ? 0 : 1) + "\n"
            + "TMNT_30FPS=" + (p == PERFORMANCE ? 0 : 1) + "\n"
            + "TMNT_FPS_LOCK=" + (p == PERFORMANCE ? 0 : 1) + "\n"
            + "TMNT_VBO=1\nTMNT_VSYNC=1\n";
        File target = new File(context.getFilesDir(), "tmnt_env.txt");
        File tmp = new File(context.getFilesDir(), "tmnt_env.tmp");
        try (FileOutputStream out = new FileOutputStream(tmp)) {
            out.write(text.getBytes(StandardCharsets.UTF_8));
            out.getFD().sync();
        }
        if (!tmp.renameTo(target)) throw new java.io.IOException("Could not save launch settings");
    }
}
